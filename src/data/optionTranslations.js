/**
 * Helper to get translated option label for any of the 10 languages
 */
export function lookupOptionTranslation(label, lang = 'en') {
  if (!label || lang === 'en') return label
  const match = OPTION_TRANSLATIONS[label]
  if (match && match[lang]) return match[lang]
  return label
}
